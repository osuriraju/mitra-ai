val localProps = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}

val debugApiUrl: String = localProps.getProperty("mitra.apiUrl", "http://10.0.2.2:4000/api/")

/**
 * Debug-only network security config: cleartext HTTP is allowed just for the emulator host, localhost and the dev
 * server named by `mitra.apiUrl`. Release ships without one, and the main manifest forbids cleartext.
 */
abstract class DevNetworkSecurityConfig : DefaultTask() {
    @get:Input abstract val hosts: SetProperty<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction fun write() {
        val domains = hosts.get().sorted().joinToString("\n") { """        <domain includeSubdomains="false">$it</domain>""" }
        val file = outputDir.file("xml/network_security_config.xml").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by :androidApp:devNetworkSecurityConfig (debug builds only). -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false"/>
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |""".trimMargin(),
        )
    }
}

val devNetworkSecurityConfig = tasks.register<DevNetworkSecurityConfig>("devNetworkSecurityConfig") {
    hosts.set(listOfNotNull("10.0.2.2", "localhost", "127.0.0.1", URI(debugApiUrl).host))
    outputDir.set(layout.buildDirectory.dir("generated/res/devNetworkSecurity"))
}

androidComponents {
    onVariants(selector().withBuildType("debug")) {
        it.sources.res?.addGeneratedSourceDirectory(devNetworkSecurityConfig, DevNetworkSecurityConfig::outputDir)
    }
}

